const ZH_REPLACEMENTS: Array<[RegExp, string]> = [
  [/\bopen 剩余\b/g, 'open'],
]

export function tr(lang: Lang, zh: string): string {
  if (lang === 'zh') return zh
  const direct = EN[zh]
  if (direct !== undefined) return direct
  let result = zh
  for (const [pattern, replacement] of ZH_REPLACEMENTS) {
    result = result.replace(pattern, replacement)
  }
  return result
}

export function fmtNum(lang: Lang, value: number): string {
  return new Intl.NumberFormat(lang === 'en' ? 'en-US' : 'zh-CN').format(
    Math.round(value),
  )
}

export function plural(
  lang: Lang,
  value: number,
  zhUnit: string,
  enSingular: string,
  enPlural: string = `${enSingular}s`,
): string {
  if (lang === 'zh') return `${fmtNum(lang, value)} ${zhUnit}`
  return `${fmtNum(lang, value)} ${value === 1 ? enSingular : enPlural}`
}

export function localizeAlgorithm(lang: Lang, label: string): string {
  if (lang === 'zh') return label
  return label
    .replaceAll('贪心最佳优先', 'Greedy best-first')
    .replaceAll('加权 A*', 'Weighted A*')
    .replaceAll('弱启发', 'weak heuristic')
    .replaceAll('拉直', 'straighten')
    .replaceAll('圆角', 'Chaikin')
    .replaceAll('抽稀', 'simplify')
}
